import AppKit

/// Pastes text into the focused text field via the clipboard.
/// With "Keep result on clipboard" on, the result stays on the clipboard after pasting; otherwise the previous
/// clipboard contents are restored. Synthesizing key events needs Accessibility permission.
enum TextInserter {
    static func insert(_ text: String) {
        if UserDefaults.standard.bool(forKey: Pref.copyToClipboard) {
            copy(text)
            pressCommandV()
            return
        }

        let pb = NSPasteboard.general
        let saved = snapshot(pb)

        pb.clearContents()
        pb.setString(text, forType: .string)
        // Mark as transient; by convention clipboard managers ignore such entries (nspasteboard.org)
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let changeCount = pb.changeCount

        pressCommandV()

        // Restore after the target app has read the clipboard; leave it alone if someone else changed it meanwhile
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            guard pb.changeCount == changeCount else { return }
            pb.clearContents()
            if !saved.isEmpty { pb.writeObjects(saved) }
        }
    }

    /// Put the text on the clipboard as a normal entry, which clipboard managers record as usual
    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private static func pressCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let v: CGKeyCode = 9  // kVK_ANSI_V
        let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        // Only ⌘, so a trigger key still held down (e.g. ⌥) doesn't turn the paste into another shortcut
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// Copy every type's data of every clipboard item
    private static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }
}
